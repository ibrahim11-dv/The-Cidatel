import assert from 'node:assert/strict'
import { Chess } from 'chess.js'
import { LocalGame, timeoutResult } from '../src/lib/localGame.js'
import { getDrawClaim, getTerminalState, materialBalance } from '../src/lib/chess.js'

const local = new LocalGame()
assert.equal(local.move({ from: 'e2', to: 'e5' }), null)
for (const move of ['e4', 'e5', 'Nf3', 'Nc6', 'Bc4', 'Nf6', 'O-O']) assert.ok(local.move(move))
assert.equal(local.chess.get('f1').type, 'r')
assert.equal(local.chess.get('g1').type, 'k')
assert.equal(local.chess.history().length, 7)
const restored = LocalGame.restore(JSON.parse(JSON.stringify(local.snapshot())))
assert.deepEqual(restored.chess.history(), local.chess.history())
assert.equal(restored.chess.fen(), local.chess.fen())
const imported = new LocalGame({ pgn: local.chess.pgn() })
assert.equal(imported.chess.fen(), local.chess.fen())

const ep = new LocalGame()
for (const move of ['e4', 'a6', 'e5', 'd5', 'exd6']) assert.ok(ep.move(move))
assert.equal(ep.chess.get('d5'), undefined)
assert.equal(materialBalance(ep.chess), 1)
const promotion = new LocalGame({ fen: '7k/P7/8/8/8/8/8/7K w - - 0 1' })
assert.ok(promotion.move({ from: 'a7', to: 'a8', promotion: 'n' }))
assert.equal(promotion.chess.get('a8').type, 'n')
assert.match(promotion.result, /insufficient/)

const mate = new LocalGame()
for (const move of ['f3', 'e5', 'g4', 'Qh4#']) assert.ok(mate.move(move))
assert.equal(mate.result, 'Black wins by checkmate')
assert.equal(mate.move('a3'), null)
assert.equal(new LocalGame({ fen: '7k/5Q2/6K1/8/8/8/8/8 b - - 0 1' }).result, 'Draw by stalemate')

const datedResult = new LocalGame({ now: 100 })
datedResult.finish('Draw by agreement', 1234)
const restoredResult = LocalGame.restore(datedResult.snapshot(), 9999)
assert.equal(datedResult.finishedAt, 1234)
assert.equal(restoredResult.finishedAt, 1234)
const legacyResult = LocalGame.restore({ ...datedResult.snapshot(), finishedAt: undefined }, 5000)
assert.equal(legacyResult.finishedAt, 5000)
const datedMate = new LocalGame({ now: 0 })
for (const move of ['f3', 'e5', 'g4', 'Qh4#']) datedMate.move(move, 4321)
assert.equal(datedMate.finishedAt, 4321)

const repetition = new LocalGame()
for (let cycle = 0; cycle < 2; cycle++) for (const move of ['Nf3', 'Nf6', 'Ng1', 'Ng8']) repetition.move(move)
assert.equal(repetition.result, null)
assert.match(getDrawClaim(repetition.chess), /threefold/)
const resumed = LocalGame.restore(repetition.snapshot())
const intended = new LocalGame()
for (const move of ['Nf3', 'Nf6', 'Ng1', 'Ng8', 'Nf3', 'Nf6', 'Ng1']) intended.move(move)
const claimFen = intended.chess.fen()
const claimHistory = intended.chess.history()
assert.equal(intended.claimDraw('e5'), false)
assert.equal(intended.claimDraw('Ng8'), true)
assert.match(intended.result, /threefold/)
assert.equal(intended.chess.fen(), claimFen)
assert.deepEqual(intended.chess.history(), claimHistory)
const intendedFifty = new LocalGame({ fen: '7k/8/8/8/8/8/R7/K7 w - - 99 50' })
assert.equal(intendedFifty.claimDraw('Ra3'), true)
assert.equal(intendedFifty.chess.history().length, 0)
assert.match(intendedFifty.result, /fifty/)
for (let cycle = 0; cycle < 2; cycle++) for (const move of ['Nf3', 'Nf6', 'Ng1', 'Ng8']) assert.ok(resumed.move(move))
assert.equal(resumed.result, 'Draw by fivefold repetition')
const fifty = new Chess('7k/8/8/8/8/8/R7/K7 w - - 100 51')
assert.equal(getTerminalState(fifty), null)
assert.match(getDrawClaim(fifty), /fifty/)
assert.match(getTerminalState(new Chess('7k/8/8/8/8/8/R7/K7 w - - 150 76')), /seventy-five/)
const restrictedCastle = new Chess('r3k2r/8/8/8/8/5r2/8/R3K2R w KQkq - 0 1')
assert.ok(!restrictedCastle.moves().includes('O-O'))

const clock = new LocalGame({ control: '1+1', now: 1000 })
clock.start(1000)
assert.equal(clock.clocks(2000).w, 59000)
assert.ok(clock.move('e4', 2000))
assert.equal(clock.clocks(3000).w, 60000)
assert.equal(clock.clocks(3000).b, 59000)
assert.equal(clock.move('e5', 62000), null)
assert.equal(clock.result, 'White wins on time')
assert.equal(clock.clocks(100000).b, 0)
assert.match(timeoutResult(new Chess('7k/8/8/8/8/8/R7/K7 w - - 0 1'), 'w'), /Draw on time/)
const running = new LocalGame({ control: '1+0', now: 0 })
running.start(0)
assert.equal(LocalGame.restore(running.snapshot(), 61000).result, 'Black wins on time')
assert.throws(() => LocalGame.restore({ version: 1, moves: [] }))
assert.throws(() => new LocalGame({ fen: '6k1/5Q2/6K1/8/8/8/8/8 w - - 0 1' }), /left its king in check/)
const agreedPgn = new LocalGame({ pgn: '[Result "1/2-1/2"]\n\n1. e4 e5 1/2-1/2' })
assert.equal(agreedPgn.result, 'Draw — imported PGN result')
assert.equal(agreedPgn.move('Nf3'), null)
const resignedPgn = new LocalGame({ pgn: '[Result "1-0"]\n\n1. e4 1-0' })
assert.match(resignedPgn.result, /White wins/)
const repeatedMoves = Array(5).fill(['Nf3', 'Nf6', 'Ng1', 'Ng8']).flat()
assert.throws(() => LocalGame.restore({ ...new LocalGame().snapshot(), moves: repeatedMoves }), /automatic game ending/)
const takeback = new LocalGame({ control: '1+1', now: 0 })
takeback.start(0)
takeback.move('e4', 1000)
takeback.move('e5', 2000)
assert.equal(takeback.takeBack('w', 3000), true)
assert.equal(takeback.chess.history().length, 0)
assert.equal(takeback.remaining.w, 59000)
assert.equal(takeback.remaining.b, 60000)
assert.equal(takeback.chess.turn(), 'w')
const blackTakeback = new LocalGame()
blackTakeback.move('e4')
assert.equal(blackTakeback.canTakeBack('b'), false)
blackTakeback.move('e5')
assert.equal(blackTakeback.takeBack('b'), true)
assert.deepEqual(blackTakeback.chess.history(), ['e4'])
console.log('Passed local rules, legal/illegal moves, castling restrictions, en passant, underpromotion, mate, stalemate, draw claims/automatic draws, clock increment/expiry, material, PGN and restoration checks.')
